// The builds: every Block in blocks/ checked (a Block that fails stops the
// build), gathered into the module; an ES module for projects and design
// tools (the Blocks, the checker, the types); the runtime as a plain script
// (window.LivingBlocks), readable and minified; then the types. The minified
// runtime has a size budget.
import { build, context } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { copyFileSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const watch = process.argv.includes('--watch');
const { version } = JSON.parse(readFileSync(new URL('../package.json', import.meta.url)));
const banner = `/*! livingblocks ${version} | (c) 2026 uxspot.io | MIT License | https://github.com/dockster/livingblocks */`;

// the Blocks, checked, then gathered by behaviour (as KINDS lists them), each
// behaviour's own Block first (its id is the kind's: carousel, then its looks)
const KIND_ORDER = ['carousel', 'accordion', 'notice', 'ring', 'showcase', 'mosaic', 'cylinder'];
const kindOf = (f) => JSON.parse(readFileSync(`blocks/${f}`, 'utf8')).kind;
const files = readdirSync('blocks')
  .filter((f) => f.endsWith('.json'))
  .sort((a, b) => {
    const ka = KIND_ORDER.indexOf(kindOf(a));
    const kb = KIND_ORDER.indexOf(kindOf(b));
    if (ka !== kb) return ka - kb;
    const ma = a === `${kindOf(a)}.json` ? 0 : 1;
    const mb = b === `${kindOf(b)}.json` ? 0 : 1;
    return ma - mb || a.localeCompare(b);
  });
const { validateBlock } = await import(new URL('../src/validate.ts', import.meta.url).href).catch(async () => {
  // node cannot load .ts: build the checker alone first
  await build({ entryPoints: ['src/validate.ts'], bundle: true, format: 'esm', outfile: 'dist/.validate.mjs', logLevel: 'warning' });
  return import(new URL('../dist/.validate.mjs', import.meta.url).href);
});
let bad = '';
for (const f of files) {
  const block = JSON.parse(readFileSync(`blocks/${f}`, 'utf8'));
  const v = validateBlock(block);
  if (!v.ok) bad += `blocks/${f}:\n  ${v.errors.join('\n  ')}\n`;
  if (block.id !== f.replace(/\.json$/, '')) bad += `blocks/${f}: its id is "${block.id}", not its file's name\n`;
}
if (bad) {
  console.error(bad.trim());
  process.exit(1);
}
writeFileSync(
  'src/registry.generated.ts',
  `// Generated by scripts/build.mjs from blocks/*.json, each checked first (validate.ts): do not edit.\nimport type { Block } from './types.js';\n${files.map((f, i) => `import b${i} from '../blocks/${f}';`).join('\n')}\n\nexport const BLOCKS: Block[] = [${files.map((_, i) => `b${i} as unknown as Block`).join(', ')}];\n`
);

rmSync('dist', { recursive: true, force: true });
const common = { bundle: true, target: 'es2020', banner: { js: banner }, legalComments: 'inline', logLevel: 'warning' };
const builds = [
  { ...common, entryPoints: ['src/index.ts'], format: 'esm', outfile: 'dist/livingblocks.mjs' },
  { ...common, entryPoints: ['src/global.ts'], format: 'iife', outfile: 'dist/livingblocks.js' },
  { ...common, entryPoints: ['src/global.ts'], format: 'iife', minify: true, outfile: 'dist/livingblocks.min.js' },
];
const stamp = () => {
  for (const f of ['livingblocks.js', 'livingblocks.min.js']) writeFileSync(`dist/${f}`, readFileSync(`dist/${f}`, 'utf8').replace('__LIVINGBLOCKS_VERSION__', version));
};
if (watch) {
  for (const b of builds) await (await context({ ...b, plugins: [{ name: 'stamp', setup: (x) => x.onEnd(() => setTimeout(stamp, 50)) }] })).watch();
  console.log('livingblocks: watching src/ and blocks/ (run the build again after adding a Block)');
} else {
  for (const b of builds) await build(b);
  stamp();
  execFileSync('npx', ['tsc', '-p', 'tsconfig.json'], { stdio: 'inherit' });
  // the runtime is a plain script: its declaration goes beside the ones tsc writes (global.d.ts imports it)
  copyFileSync('src/runtime.d.ts', 'dist/runtime.d.ts');
  // the ring (0.2: a ring of cards in depth turned by the scroll and a drag) takes it from 5.2 to 6.9
  // the showcase (a hero of stacked slides with line reveals) and the mosaic (a dense media grid) take it to 9.9
  // the cylinder (0.3: lines of text turned by the scroll while held) and its Block take it to 10.7
  // 11.5 since 0.4.0 (2026-10-17): the ring's Previous, Next and Pause parts and its rest on hover and focus (WCAG 2.5.7, 2.2.2)
  const BUDGET = { 'livingblocks.min.js': 11.5 };
  let over = '';
  for (const f of ['livingblocks.mjs', 'livingblocks.js', 'livingblocks.min.js']) {
    const b = readFileSync(`dist/${f}`);
    const gz = gzipSync(b).length / 1024;
    console.log(`${f.padEnd(18)} ${(b.length / 1024).toFixed(1).padStart(6)} KB, ${gz.toFixed(1).padStart(5)} KB gzipped${BUDGET[f] ? ` (budget ${BUDGET[f]})` : ''}`);
    if (BUDGET[f] && gz > BUDGET[f]) over += `${f} is ${gz.toFixed(1)} KB gzipped, over its ${BUDGET[f]} KB budget\n`;
  }
  console.log(`${files.length} Blocks: ${files.map((f) => f.replace('.json', '')).join(', ')}`);
  if (over) {
    console.error(over.trim());
    process.exit(1);
  }
}
